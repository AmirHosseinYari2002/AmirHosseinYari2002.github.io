#!/usr/bin/env python3
"""Build trace-task-a/traces.js from the frozen pilot bundle.

Usage:
  python3 build_traces.py /path/to/frozen-pilot-v2 ../traces.js

Only the source text and the problem statement are exported. The LLM segmentation is
deliberately NOT written to the website, so annotators segment independently.
Character offsets in the website refer to `completion_text` exactly as stored in
deepseek-pilot/results/trajectories.jsonl (the trailing end-of-sentence token is hidden).
"""
import json, sys, os, hashlib

EOS = "<｜end▁of▁sentence｜>"
# Fixed presentation order (shortest first) - identical for every annotator.
ORDER = ["tr_c984bb200fcad93b2061", "tr_bd762da13a9edec43b6e", "tr_1e2d7e5f49120fe5a74d", "tr_2eb4a94d173163db6303"]

def main(root, out):
    res = os.path.join(root, "deepseek-pilot", "results")
    traj = {}
    with open(os.path.join(res, "trajectories.jsonl"), encoding="utf-8") as f:
        for line in f:
            r = json.loads(line); traj[r["trace_id"]] = r
    probs = {}
    with open(os.path.join(res, "problems.jsonl"), encoding="utf-8") as f:
        for line in f:
            r = json.loads(line); probs[r["problem_id"]] = r
    items = []
    for n, tid in enumerate(ORDER, 1):
        t = traj[tid]
        text = t["completion_text"]
        if text.endswith(EOS):
            text = text[: -len(EOS)]
        items.append({
            "id": tid,
            "label": "Trace %d" % n,
            "problem_id": t["problem_id"],
            "question": probs[t["problem_id"]]["question"],
            "text": text,
            "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
            "words": len(text.split()),
        })
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_traces.py - do not edit by hand.\n")
        f.write("window.TRACES = ")
        json.dump(items, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    for it in items:
        print(it["label"], it["id"], it["words"], "words", len(it["text"]), "chars")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
